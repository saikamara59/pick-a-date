// Generates src/components/iconPaths.ts: the duotone SVG markup of the few Phosphor icons we use,
// so the app doesn't bundle every weight of every icon. Run: node scripts/gen-icons.mjs
// Icons: Phosphor Icons (MIT) — https://phosphoricons.com
import { writeFileSync } from 'node:fs'
import { createElement } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import * as P from '@phosphor-icons/react'

const NAMES = [
  'Bank', 'BowlFood', 'BowlSteam', 'BowlingBall', 'BuildingApartment', 'Champagne', 'Coffee', 'Compass', 'Couch',
  'Cow', 'Egg', 'FishSimple', 'ForkKnife', 'GameController', 'Gift', 'Golf', 'Hamburger', 'IceCream', 'LockKey',
  'MapPin', 'MaskHappy', 'MicrophoneStage', 'PaintBrush', 'Pepper', 'Pizza', 'Popcorn', 'Shrimp', 'Snowflake',
  'Ticket', 'Tree',
]

const out = {}
for (const n of NAMES) {
  const svg = renderToStaticMarkup(createElement(P[n], { weight: 'duotone' }))
  out[n] = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '')
}
const body = Object.entries(out).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join('\n')
writeFileSync(
  'src/components/iconPaths.ts',
  `// Generated by scripts/gen-icons.mjs from Phosphor Icons (MIT, phosphoricons.com). Do not edit by hand.\n// Inner markup of each icon's duotone weight, for a 256×256 viewBox.\nexport const ICONS = {\n${body}\n} as const\n\nexport type IconName = keyof typeof ICONS\n`,
)
console.log(`wrote ${NAMES.length} icons`)
